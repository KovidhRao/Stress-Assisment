/**
 * Universal translation helper with robust fallback to English
 */
export function t(key: string, lang: string = 'en'): string {
  let code: SupportedLanguage = 'en'
  const clean = (lang || '').toLowerCase().trim()

  if (clean === 'hi' || clean.includes('hindi') || clean.includes('हिंदी')) code = 'hi'
  else if (clean === 'kn' || clean.includes('kannada') || clean.includes('ಕನ್ನಡ')) code = 'kn'
  else if (clean === 'te' || clean.includes('telugu') || clean.includes('తెలుగు')) code = 'te'
  else if (clean === 'ta' || clean.includes('tamil') || clean.includes('தமிழ்')) code = 'ta'
  else if (clean === 'mr' || clean.includes('marathi') || clean.includes('मराठी')) code = 'mr'
  else if (clean === 'bn' || clean.includes('bengali') || clean.includes('বাংলা')) code = 'bn'
  else if (clean === 'gu' || clean.includes('gujarati') || clean.includes('ગુજરાતી')) code = 'gu'
  else code = 'en'

  const dict = TRANSLATIONS[code] || TRANSLATIONS.en
  return dict[key] || TRANSLATIONS.en[key] || key
}

export function normalizeLangCode(lang?: string): SupportedLanguage {
  const clean = (lang || '').toLowerCase().trim()
  if (clean === 'hi' || clean.includes('hindi') || clean.includes('हिंदी')) return 'hi'
  if (clean === 'kn' || clean.includes('kannada') || clean.includes('ಕನ್ನಡ')) return 'kn'
  if (clean === 'te' || clean.includes('telugu') || clean.includes('తెలుగు')) return 'te'
  if (clean === 'ta' || clean.includes('tamil') || clean.includes('தமிழ்')) return 'ta'
  if (clean === 'mr' || clean.includes('marathi') || clean.includes('मराठी')) return 'mr'
  if (clean === 'bn' || clean.includes('bengali') || clean.includes('বাংলা')) return 'bn'
  if (clean === 'gu' || clean.includes('gujarati') || clean.includes('ગુજરાતી')) return 'gu'
  return 'en'
}

/**
 * Helper to dynamically translate activity titles, descriptions, and timestamps
 */
export function translateActivity(
  act: { title: string; description: string; timestamp: string },
  lang: string
): { title: string; description: string; timestamp: string } {
  let title = act.title
  let description = act.description
  let timestamp = act.timestamp

  // Timestamps
  if (timestamp === '1 hour ago' || timestamp.includes('1 hour')) timestamp = t('time_1_hour_ago', lang)
  else if (timestamp === '3 hours ago' || timestamp.includes('3 hour')) timestamp = t('time_3_hours_ago', lang)
  else if (timestamp === 'Yesterday' || timestamp.toLowerCase() === 'yesterday') timestamp = t('time_yesterday', lang)
  else if (timestamp === 'Just now' || timestamp.toLowerCase() === 'just now') timestamp = t('time_just_now', lang)
  else if (timestamp === '2 days ago' || timestamp.includes('2 day')) timestamp = t('time_2_days_ago', lang)

  // Story activity
  if (title.includes('Story safely submitted') || title.includes('Story #') || title.includes('submitted')) {
    title = t('act_story_submitted_title', lang)
    description = t('act_story_submitted_desc', lang)
  }
  // Mood activity
  else if (title.includes('Daily mood') || title.includes('mood')) {
    const moodName = title.includes('Calm') ? t('mood_calm', lang)
      : title.includes('Okay') ? t('mood_okay', lang)
      : title.includes('Stressed') ? t('mood_stressed', lang)
      : title.includes('Anxious') ? t('mood_anxious', lang)
      : title.includes('Overwhelmed') ? t('mood_overwhelmed', lang)
      : 'Stressed'
    title = t('act_mood_recorded_title', lang).replace('{mood}', moodName)
    description = t('act_mood_recorded_desc', lang)
  }
  // Breathing activity
  else if (title.includes('Box Breathing') || title.includes('Breathing session')) {
    title = t('act_breathing_completed_title', lang)
    description = t('act_breathing_completed_desc', lang)
  }
  // Psychiatrist assigned
  else if (title.includes('Psychiatrist assigned') || title.includes('Doctor assigned')) {
    title = t('act_psychiatrist_assigned_title', lang)
    description = t('act_psychiatrist_assigned_desc', lang)
  }
  // Consultation booked
  else if (title.includes('Consultation') || title.includes('confirmed with')) {
    const docName = title.split('with ')[1] || 'Doctor'
    title = t('act_consultation_confirmed_title', lang).replace('{name}', docName)
  }
  // Contact added
  else if (title.includes('Added ') && title.includes('Support Circle')) {
    const contactName = title.replace('Added ', '').replace(' to Support Circle', '')
    title = t('act_contact_added_title', lang).replace('{name}', contactName)
  }

  return { title, description, timestamp }
}
