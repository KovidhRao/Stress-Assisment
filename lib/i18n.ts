/**
 * Universal translation helper with robust fallback to English
 */
export function t(key: string, lang: string = 'en'): string {
  let code: SupportedLanguage = 'en'
  const clean = (lang || '').toLowerCase().trim()

  if (clean === 'hi' || clean.includes('hindi') || clean.includes('हिंदी')) code = 'hi'
  else if (clean === 'kn' || clean.includes('kannada') || clean.includes('ಕನ್ನಡ')) code = 'kn'
  else if (clean === 'te' || clean.includes('telugu') || clean.includes('తెలుగు')) code = 'te'
  else if (clean === 'ta' || clean.includes('tamil') || clean.includes('தமிழ்')) code = 'ta'
  else if (clean === 'mr' || clean.includes('marathi') || clean.includes('मराठी')) code = 'mr'
  else if (clean === 'bn' || clean.includes('bengali') || clean.includes('বাংলা')) code = 'bn'
  else if (clean === 'gu' || clean.includes('gujarati') || clean.includes('ગુજરાતી')) code = 'gu'
  else code = 'en'

  const dict = TRANSLATIONS[code] || TRANSLATIONS.en
  return dict[key] || TRANSLATIONS.en[key] || key
}

export function normalizeLangCode(lang?: string): SupportedLanguage {
  const clean = (lang || '').toLowerCase().trim()
  if (clean === 'hi' || clean.includes('hindi') || clean.includes('हिंदी')) return 'hi'
  if (clean === 'kn' || clean.includes('kannada') || clean.includes('ಕನ್ನಡ')) return 'kn'
  if (clean === 'te' || clean.includes('telugu') || clean.includes('తెలుగు')) return 'te'
  if (clean === 'ta' || clean.includes('tamil') || clean.includes('தமிழ்')) return 'ta'
  if (clean === 'mr' || clean.includes('marathi') || clean.includes('मराठी')) return 'mr'
  if (clean === 'bn' || clean.includes('bengali') || clean.includes('বাংলা')) return 'bn'
  if (clean === 'gu' || clean.includes('gujarati') || clean.includes('ગુજરાતી')) return 'gu'
  return 'en'
}

